import React from 'react';
import { Todo } from '../../types/Todo';

interface Props {
  todos: Todo[];
  handleSelected: (todo: number | null) => void;
  selectedTodo: number | null;
}

export const TodoList: React.FC<Props> = ({
  todos,
  handleSelected,
  selectedTodo,
}) => (
  <table className="table is-narrow is-fullwidth">
    <thead>
      <tr>
        <th>#</th>
        <th>
          <span className="icon">
            <i className="fas fa-check" />
          </span>
        </th>
        <th>Title</th>
        <th> </th>
      </tr>
    </thead>

    <tbody>
      {todos.map(todo => (
        <tr
          data-cy="todo"
          className={
            selectedTodo === todo.id ? 'has-background-info-light' : ''
          }
          key={todo.id}
        >
          <td className="is-vcentered">{todo.id}</td>
          <td className="is-vcentered">
            {todo.completed && (
              <span className="ion" data-cy="iconCompleted">
                <i className="fas fa-check" />
              </span>
            )}
          </td>
          <td className="is-vcentered is-expanded">
            <p
              className={
                todo.completed ? 'has-text-success' : 'has-text-danger'
              }
            >
              {todo.title}
            </p>
          </td>
          <td className="has-text-right is-vcentered">
            <button
              data-cy="selectButton"
              className="button"
              type="button"
              onClick={() => handleSelected(todo.id)}
            >
              <span className="icon">
                <i
                  className={
                    selectedTodo === todo.id ? 'far fa-eye-slash' : 'far fa-eye'
                  }
                />
              </span>
            </button>
          </td>
        </tr>
      ))}
    </tbody>
  </table>
);
